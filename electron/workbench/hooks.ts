const ours = (v: any) =>
  /Yami\.Hook\.exe|yami-agent-plugin/.test(JSON.stringify(v));
const hash = (text: string) => createHash("sha256").update(text).digest("hex");
export function hookPlan(
  agent: string,
  install: boolean,
  relayConfig: string,
  home = os.homedir(),
) {
  if (agent === "opencode") {
    const file = path.join(
      (home === os.homedir() && process.env.XDG_CONFIG_HOME) ||
        path.join(home, ".config"),
      "opencode",
      "plugins",
      "yami.js",
    );
    const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (before && !before.startsWith("// yami-agent-plugin"))
      throw new Error(
        "An unrelated file already uses the Yami plugin path; nothing was changed.",
      );
    const after = install
      ? `// yami-agent-plugin: generated by Yami\nimport {spawn} from 'node:child_process';\nconst relay=${JSON.stringify(helperPath("Yami.Hook.exe"))}, config=${JSON.stringify(relayConfig)};\nexport const YamiPlugin=async ({directory})=>{\nconst send=(event,data={})=>{const child=spawn(relay,['opencode',event,config],{windowsHide:true,stdio:['pipe','ignore','ignore']});child.on('error',()=>{});child.stdin.on('error',()=>{});child.stdin.end(JSON.stringify({...data,cwd:directory}));const timer=setTimeout(()=>child.kill(),2000);child.on('exit',()=>clearTimeout(timer));};\nreturn {event:async ({event})=>{const p=event.properties||{};send(event.type,{session_id:p.sessionID||p.session?.id,message:p.error?.message});},'tool.execute.before':async (input)=>send('PreToolUse',{session_id:input.sessionID,tool_name:input.tool}),'tool.execute.after':async (input)=>send('PostToolUse',{session_id:input.sessionID,tool_name:input.tool})};\n};\n`
      : "";
    return {
      agent,
      install,
      file,
      before,
      after,
      fingerprint: hash(before),
      note: "Restart OpenCode to load the Yami activity plugin. Approvals remain in OpenCode.",
    };
  }
  const spec = specs[agent];
  if (!spec)
    throw new Error(
      "This agent uses the OpenCode plugin or the documented relay protocol.",
    );
  const file = path.join(home, spec.file);
  const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const root = before ? JSON.parse(before) : {};
  if (
    !root ||
    Array.isArray(root) ||
    typeof root !== "object" ||
    (root.hooks &&
      (Array.isArray(root.hooks) || typeof root.hooks !== "object"))
  )
    throw new Error(
      "Agent settings have an unexpected format; nothing was changed.",
    );
  const hooks = { ...root.hooks };
  for (const [event, list] of Object.entries(hooks)) {
    if (!Array.isArray(list))
      throw new Error("Agent hooks have an unexpected format.");
    hooks[event] = list.flatMap((entry: any) => {
      if (entry.hooks) {
        if (!Array.isArray(entry.hooks)) throw new Error("Invalid hook group.");
        const kept = entry.hooks.filter((h: any) => !ours(h));
        return kept.length ? [{ ...entry, hooks: kept }] : [];
      }
      return ours(entry) ? [] : [entry];
    });
  }
  if (install)
    for (const event of spec.events) {
      const quote = (v: string) =>
        spec.powershell
          ? "'" + v.replaceAll("'", "''") + "'"
          : agent === "codex"
            ? '"' + v.replaceAll("\\", "/") + '"'
            : "'" + v.replaceAll("\\", "/").replaceAll("'", "'\\''") + "'";
      const command = `${spec.powershell ? "& " : ""}${quote(helperPath("Yami.Hook.exe"))} ${agent} ${event} ${quote(relayConfig)}`;
      const timeout =
        /Permission/.test(event) || event === "permissionRequest"
          ? 120
          : agent === "codex" && event === "SessionEnd"
            ? 3
            : 5;
      const entry = spec.copilot
        ? {
            type: "command",
            powershell: command,
            bash: `'${helperPath("Yami.Hook.exe").replaceAll("\\", "/").replaceAll("'", "'\\''")}' ${agent} ${event} '${relayConfig.replaceAll("\\", "/").replaceAll("'", "'\\''")}'`,
            timeoutSec: timeout,
          }
        : agent === "cursor"
          ? { command }
          : {
              ...(agent === "codex" ? {} : { matcher: "*" }),
              hooks: [
                {
                  type: "command",
                  command,
                  timeout: spec.powershell ? timeout * 1000 : timeout,
                },
              ],
            };
      hooks[event] = [...(hooks[event] || []), entry];
    }
  if (agent === "claude" && install) {
    const quote = (v: string) =>
      "'" + v.replaceAll("\\", "/").replaceAll("'", "'\\''") + "'";
    const command = `${quote(helperPath("Yami.Hook.exe"))} claude PreToolUse ${quote(relayConfig)}`;
    hooks.PreToolUse = [
      ...hooks.PreToolUse.filter((g: any) => !ours(g)),
      { matcher: "*", hooks: [{ type: "command", command, timeout: 5 }] },
      {
        matcher: "AskUserQuestion",
        hooks: [
          {
            type: "command",
            command: command.replace(
              " claude PreToolUse ",
              " claude Question ",
            ),
            timeout: 120,
          },
        ],
      },
    ];
  }
  for (const event of Object.keys(hooks))
    if (!hooks[event].length) delete hooks[event];
  const after =
    JSON.stringify(
      { ...root, ...(spec.copilot ? { version: 1 } : {}), hooks },
      null,
      2,
    ) + "\n";
  return {
    agent,
    install,
    file,
    before,
    after,
    fingerprint: hash(before),
    note:
      agent === "codex"
        ? "Start Codex and review the new hooks with /hooks."
        : "Restart this agent to load its hooks.",
  };
}
export function applyHookPlan(
  agent: string,
  install: boolean,
  fingerprint: string,
  config: string,
  home = os.homedir(),
) {
  const plan = hookPlan(agent, install, config, home);
  if (plan.fingerprint !== fingerprint)
    throw new Error(
      "Agent settings changed since the preview. Review the new preview first.",
    );
  fs.mkdirSync(path.dirname(plan.file), { recursive: true });
  let backup = "";
  if (plan.before) {
    backup = plan.file + ".yami-backup-" + Date.now();
    fs.copyFileSync(plan.file, backup, fs.constants.COPYFILE_EXCL);
  }
  fs.writeFileSync(plan.file + ".yami.tmp", plan.after);
  fs.renameSync(plan.file + ".yami.tmp", plan.file);
  return { backup, note: plan.note };
}
