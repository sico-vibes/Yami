import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";
const root = path.resolve("Documentation");
const manifest = JSON.parse(
  fs.readFileSync(path.join(root, "docs-manifest.json"), "utf8"),
);
const documents = manifest.documents.map((d) => {
  const file = path.resolve(root, d.path);
  if (!file.startsWith(root + path.sep))
    throw Error("Documentation path escapes root");
  const content = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  if (!content.trim()) throw Error(`Empty documentation: ${d.path}`);
  return { ...d, content };
});
fs.mkdirSync(path.join(root, "viewer"), { recursive: true });
fs.writeFileSync(
  path.join(root, "viewer/content.js"),
  "/* Generated by npm run docs. Edit Markdown sources. */\nwindow.YAMI_DOCS=" +
    JSON.stringify(documents).replaceAll("<", "\\u003c") +
    ";\n",
);
await build({
  entryPoints: ["Documentation/viewer/source.js"],
  bundle: true,
  format: "iife",
  minify: true,
  outfile: "Documentation/viewer/app.js",
  legalComments: "eof",
});
fs.mkdirSync(path.join(root, "assets/brand"), { recursive: true });
fs.copyFileSync(
  "public/yami-icon.png",
  path.join(root, "assets/brand/yami-icon.png"),
);
const fontDir = "node_modules/@fontsource-variable/rubik/files";
const font = fs
  .readdirSync(fontDir)
  .find((f) => f === "rubik-latin-wght-normal.woff2");
if (!font) throw Error("Rubik Latin variable font missing");
fs.copyFileSync(
  path.join(fontDir, font),
  path.join(root, "assets/brand/rubik-latin.woff2"),
);
fs.copyFileSync(
  "node_modules/marked/LICENSE",
  path.join(root, "viewer/marked-LICENSE.md"),
);
fs.copyFileSync(
  "node_modules/dompurify/LICENSE",
  path.join(root, "viewer/DOMPurify-LICENSE.txt"),
);
console.log(
  `Built ${documents.length} guides. Open Documentation/index.html directly; no server required.`,
);
